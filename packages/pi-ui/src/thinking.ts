/**
 * Codex-style collapsed thinking display.
 *
 * While a thinking run streams, the transcript shows a tool-row-style header
 * plus the current tail line of the reasoning:
 *
 *   • Thinking 4s
 *     └ The user wants me to change the thinking display, so first I need…
 *
 * Once the run closes (the model moved on to text or tool calls, or the
 * message finished), it collapses to the duration header plus a one-line
 * summary of the reasoning:
 *
 *   • Thought for 12s
 *     └ I patched AssistantMessageComponent to render collapsed thinking rows.
 *
 * The rows reuse pi-ui's tool-row look (dot + bold verb, `└` continuation in
 * the thinking color), so thinking reads like any other tool activity.
 *
 * The summary sentence is generated by the model itself: a nested
 * `completeSimple` call condenses the run into one sentence. Until it lands
 * (typically 1–2s), the run's last line — usually the model's own conclusion
 * — stands in as the interim summary and is replaced in place. Short runs
 * (≤2 lines) skip the call; failures keep the interim line. Like
 * pi-smart-flow's compact-thinking, summaries are TUI-only: the assistant
 * message and its thinking signatures are never modified.
 *
 * Timing, identity, and Pi's streaming protocol: `message_update` events
 * carry a fresh `{ ...partial }` shallow copy on EVERY delta (pi-agent-core
 * agent-loop.js), so per-object WeakMap tracking alone would reset each
 * delta. Durations are therefore accumulated in module-level live arrays
 * keyed by run index, and committed into a WeakMap on the final message
 * object at `message_end` — the object later chat rebuilds reuse.
 *
 * ctrl+t toggles between this collapsed pair and Pi's full italic thinking
 * markdown. Because both states of Pi's old "Hide thinking" setting are now
 * superseded (collapsed summary / expanded full text), the settings entry is
 * removed from the settings list.
 *
 * Mechanics, following tools.ts conventions:
 *   - `AssistantMessageComponent.prototype.updateContent` is re-implemented
 *     for messages that contain thinking and delegated to the original for
 *     everything else (so text blocks keep Pi's exact markdown pipeline).
 *     Any unexpected shape falls back to the original renderer.
 *   - `InteractiveMode.prototype.toggleThinkingBlockVisibility` (the ctrl+t
 *     action) is wrapped to flip this module's expansion flag; the original
 *     still performs the chat rebuild and streaming-component refresh.
 *   - `SettingsList.prototype.render` drops the "hide-thinking" item.
 *   - `pi.on("message_update")` keeps the freshest ExtensionContext (model +
 *     API key) for summary calls; the editor factory hand-off captures the
 *     TUI so a landed summary can request an immediate re-render.
 */

